#!/usr/bin/env bash
# =============================================================================
# Lunex — regenerate the Cloudflare snippets used by nginx (IN-11).
#
#   docker/snippets/cloudflare-realip.conf   set_real_ip_from + CF-Connecting-IP
#   docker/snippets/cloudflare-allow.conf    allow <CF ranges>; deny all;
#
# Only enable these includes once the zone is proxied through Cloudflare
# (orange cloud) — see docs/security/cloudflare-waf.md.
#
# Usage (weekly cron on the VPS, as the repo owner):
#   15 4 * * 1  /opt/lunex/docker/refresh-cloudflare-ips.sh --reload
#
# Fails closed: if either list cannot be fetched, is empty, or contains
# anything that is not a CIDR, the existing snippets are left untouched.
# =============================================================================
set -euo pipefail

SNIPPETS_DIR="${SNIPPETS_DIR:-$(cd "$(dirname "$0")" && pwd)/snippets}"
COMPOSE_FILE="${COMPOSE_FILE:-$(cd "$(dirname "$0")" && pwd)/docker-compose.prod.yml}"
RELOAD=false
[[ "${1:-}" == "--reload" ]] && RELOAD=true

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

fetch() {
  curl -fsS --max-time 20 --proto '=https' --tlsv1.2 "$1" -o "$2"
}

fetch https://www.cloudflare.com/ips-v4 "$tmp/v4"
fetch https://www.cloudflare.com/ips-v6 "$tmp/v6"

V4_RE='^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$'
V6_RE='^[0-9a-fA-F:]+/[0-9]{1,3}$'
for f in v4 v6; do
  # normalise: strip CR / blank lines; awk also restores a missing final
  # newline (the CF lists have none, which would make `read` drop a range).
  tr -d '\r' <"$tmp/$f" | awk 'NF' >"$tmp/$f.clean"
  [[ -s "$tmp/$f.clean" ]] || { echo "empty $f list — abort" >&2; exit 1; }
done
grep -Evq "$V4_RE" "$tmp/v4.clean" && { echo "unexpected v4 entry — abort" >&2; exit 1; }
grep -Evq "$V6_RE" "$tmp/v6.clean" && { echo "unexpected v6 entry — abort" >&2; exit 1; }

stamp="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
{
  echo "# Generated by docker/refresh-cloudflare-ips.sh at ${stamp} — do not edit."
  echo "# Trust CF-Connecting-IP ONLY when the TCP peer is a Cloudflare edge."
  while read -r c; do echo "set_real_ip_from ${c};"; done <"$tmp/v4.clean"
  while read -r c; do echo "set_real_ip_from ${c};"; done <"$tmp/v6.clean"
  echo "real_ip_header CF-Connecting-IP;"
} >"$tmp/cloudflare-realip.conf"
{
  echo "# Generated by docker/refresh-cloudflare-ips.sh at ${stamp} — do not edit."
  echo "# Origin lock: only Cloudflare edges may connect (use inside server{})."
  while read -r c; do echo "allow ${c};"; done <"$tmp/v4.clean"
  while read -r c; do echo "allow ${c};"; done <"$tmp/v6.clean"
  echo "deny all;"
} >"$tmp/cloudflare-allow.conf"

mkdir -p "$SNIPPETS_DIR"
install -m 0644 "$tmp/cloudflare-realip.conf" "$SNIPPETS_DIR/cloudflare-realip.conf"
install -m 0644 "$tmp/cloudflare-allow.conf" "$SNIPPETS_DIR/cloudflare-allow.conf"
echo "Cloudflare snippets refreshed in $SNIPPETS_DIR"

if $RELOAD; then
  docker compose -f "$COMPOSE_FILE" exec -T nginx nginx -t
  docker compose -f "$COMPOSE_FILE" exec -T nginx nginx -s reload
fi
